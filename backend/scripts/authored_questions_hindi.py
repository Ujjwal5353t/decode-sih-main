@dataclass
class AQ:
    """One authored question. Mirrors Question's content fields 1:1 —
    the caller constructs a Question(...) row from this plus
    topic_id/subject/class_number/generation_source/generation_batch."""

    question_text: str
    options: list[str]
    correct_option_index: int
    explanation: str = ""
    image_emoji: Optional[str] = None
    image_asset_key: Optional[str] = None
    option_emojis: Optional[list[str]] = None
    option_asset_keys: Optional[list[str]] = None


def q(
    question_text: str,
    options: list[str],
    correct_option_index: int,
    explanation: str,
    image_asset_key: Optional[str] = None,
) -> AQ:
    return AQ(
        question_text=question_text,
        options=options,
        correct_option_index=correct_option_index,
        explanation=explanation,
        image_asset_key=image_asset_key,
    )


