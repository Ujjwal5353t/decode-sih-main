def _validate(topic_code: str, aq: AQ) -> None:
    """Same belt-and-suspenders checks scripts/generate_template_questions.py
    applies before any row reaches the DB."""
    assert len(aq.options) == 4, f"{topic_code}: expected 4 options, got {aq.options!r}"
    assert len(set(aq.options)) == 4, f"{topic_code}: duplicate option values {aq.options!r}"
    assert 0 <= aq.correct_option_index <= 3, f"{topic_code}: bad correct_option_index"
    assert not (aq.image_asset_key and aq.image_emoji), (
        f"{topic_code}: image_asset_key and image_emoji both set"
    )
    assert not (aq.option_asset_keys and aq.option_emojis), (
        f"{topic_code}: option_asset_keys and option_emojis both set"
    )
    if aq.image_asset_key:
        assert aq.image_asset_key in ALL_ASSET_KEYS, (
            f"{topic_code}: unknown image_asset_key {aq.image_asset_key!r}"
        )
    if aq.option_asset_keys:
        assert len(aq.option_asset_keys) == 4, f"{topic_code}: option_asset_keys must have 4 entries"
        for key in aq.option_asset_keys:
            assert key in ALL_ASSET_KEYS, f"{topic_code}: unknown option_asset_key {key!r}"
    if aq.option_emojis:
        assert len(aq.option_emojis) == 4, f"{topic_code}: option_emojis must have 4 entries"


async def _fetch_topics() -> dict[str, Topic]:
    async with AsyncSessionFactory() as session:
        result = await session.execute(
            select(Topic).where(Topic.subject == SUBJECT)
        )
        return {t.code: t for t in result.scalars().all()}


async def main() -> None:
    parser = argparse.ArgumentParser(
        description="Author and load an original Hindi diagnostic-quiz question bank."
    )
    parser.add_argument("--dry-run", action="store_true", help="Print output, do not write to DB.")
    args = parser.parse_args()

    topics = await _fetch_topics()
    if not topics:
        print(f"No {SUBJECT} topics found. Has the DB been seeded (curriculum_seed)?")
        return

    missing = [code for code in TOPIC_QUESTIONS if code not in topics]
    if missing:
        raise SystemExit(f"Topic code(s) not found in DB: {missing}")

    uncovered = [code for code in topics if code not in TOPIC_QUESTIONS]
    if uncovered:
        print(f"[warn] {len(uncovered)} {SUBJECT} topic(s) have no authored questions: {uncovered}")

    total_questions = 0
    for code, questions in TOPIC_QUESTIONS.items():
        assert len(questions) >= 8, f"{code}: only {len(questions)} questions authored, need >= 8"
        for aq in questions:
            _validate(code, aq)
        total_questions += len(questions)

    print(f"Validated {total_questions} authored questions across {len(TOPIC_QUESTIONS)} topics.")

    if args.dry_run:
        for code, questions in list(TOPIC_QUESTIONS.items())[:2]:
            print(f"\n[dry-run] {code}: {len(questions)} questions")
            for aq in questions[:2]:
                print(f"  Q: {aq.question_text}")
                print(f"  Options: {aq.options}  Correct: {aq.correct_option_index}")
                if aq.image_asset_key:
                    print(f"  Image asset: {aq.image_asset_key}")
        print("\n[dry-run] No DB writes performed.")
        return

    generation_batch = date.today().isoformat()

    async with AsyncSessionFactory() as session:
        deactivated = await session.execute(
            update(Question)
            .where(Question.subject == SUBJECT, Question.is_active == True)  # noqa: E712
            .values(is_active=False)
        )
        await session.commit()
        print(f"Deactivated {deactivated.rowcount} existing active {SUBJECT} question(s).")

        inserted = 0
        for code, questions in TOPIC_QUESTIONS.items():
            topic = topics[code]
            for aq in questions:
                session.add(
                    Question(
                        topic_id=topic.id,
                        subject=SUBJECT,
                        class_number=topic.class_number,
                        question_text=aq.question_text,
                        options=aq.options,
                        correct_option_index=aq.correct_option_index,
                        explanation=aq.explanation or None,
                        image_emoji=aq.image_emoji,
                        image_asset_key=aq.image_asset_key,
                        option_emojis=aq.option_emojis,
                        option_asset_keys=aq.option_asset_keys,
                        generation_source=GENERATION_SOURCE,
                        generation_batch=generation_batch,
                        module_id=None,
                        branch_name=None,
                        reviewed=False,
                        is_active=True,
                    )
                )
                inserted += 1
        await session.commit()
        print(f"Inserted {inserted} new {SUBJECT} question rows "
              f"(generation_source={GENERATION_SOURCE!r}, generation_batch={generation_batch!r}).")


if __name__ == "__main__":
    asyncio.run(main())
